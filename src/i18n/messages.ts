export function translateMessage(
  language: InterfaceLanguage,
  message: string,
  values: Record<string, string | number> = {},
): string {
  let translated = language === "en" ? (englishMessages[message] ?? message) : message;
  for (const [key, value] of Object.entries(values)) {
    translated = translated.replaceAll(`{{${key}}}`, String(value));
  }
  return translated;
}

export function translatePlural(
  language: InterfaceLanguage,
  singular: string,
  plural: string,
  count: number,
  values: Record<string, string | number> = {},
): string {
  return translateMessage(language, count === 1 ? singular : plural, { ...values, count });
}

export function getInitialInterfaceLanguage(
  storedValue: string | null,
  browserLanguage: string | undefined,
): InterfaceLanguage {
  if (storedValue === "zh-CN" || storedValue === "en") return storedValue;
  return browserLanguage?.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}

export function saveInterfaceLanguage(
  storage: Pick<Storage, "setItem">,
  language: InterfaceLanguage,
): void {
  storage.setItem(INTERFACE_LANGUAGE_KEY, language);
}


